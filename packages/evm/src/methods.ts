/**
 * Список перехватываемых методов EIP-1193 — константа семейного слоя.
 *
 * Свойство списка (§6.4 плана): он исчерпывает **денежную поверхность
 * протокола**, то есть точки, где действие ещё можно предотвратить. Это факт о
 * протоколе, а не гипотеза о партнёре: «догейтить нестандартное» делается
 * server-side через реестр, а не правкой этого списка. Клиент не решает,
 * гейтится ли действие, — всё перехваченное уходит на сервер.
 *
 * Состав зафиксирован ревизией в HAD-333:
 *
 * | Метод | Решение | Почему |
 * | -- | -- | -- |
 * | `eth_sendTransaction` | гейтим | отправка транзакции — основная точка |
 * | `eth_signTransaction` | гейтим | подпись без бродкаста: тот же конверт параметров, деньги подписываются здесь |
 * | `wallet_sendCalls` | гейтим | EIP-5792 батч, оценивается покалльно |
 * | `eth_signTypedData`, `_v3`, `_v4` | гейтим | permit/Permit2 — аппрув без транзакции |
 * | `eth_sendRawTransaction` | **не гейтим** | см. ниже |
 * | `personal_sign`, `eth_sign` | не гейтим | не денежная поверхность протокола: произвольный байтстрок, чаще всего SIWE-логин. Партнёру с подписанными офчейн-ордерами доступен manual `guard()` |
 *
 * **`eth_sendRawTransaction` — вердикт: не включаем в P0.** Транзакция к этому
 * моменту уже подписана, поэтому гейт здесь предотвращает только бродкаст —
 * а подписанную транзакцию можно отправить в любой публичный RPC мимо нас.
 * Это не точка удушения, а кооперативная проверка со слабой гарантией; по
 * «лестнице гарантий» (§7) такой обход закрывается реконсиляцией журнала либо
 * серверным evaluate, а не перехватом в браузере. Приложение, которое
 * подписывает локально, — это embedded-кошелёк: для него гейт ставится
 * action-level адаптером ДО подписи (§6.4, уровень 2), где вердикт ещё может
 * предотвратить действие. Плюс осмысленные факты потребовали бы RLP-декодера
 * подписанной транзакции: его ошибка исказила бы факты и, значит, решение —
 * цена выше пользы от заведомо обходимого гейта.
 */
